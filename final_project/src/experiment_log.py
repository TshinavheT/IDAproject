"""
Write docs/experiment_log.md: every experiment, its configuration and its result,
generated from the files in results/ so it always matches the latest run.
Run from the project root:  python src/experiment_log.py
"""

import json
from datetime import date
from pathlib import Path

import pandas as pd

from models import SEED, build_models

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RESULTS = PROJECT_ROOT / "results"
OUT = PROJECT_ROOT / "docs" / "experiment_log.md"


def md_table(df, floatfmt="{:.3f}"):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def model_config(name, model):
    clf = model.named_steps["model"] if hasattr(model, "named_steps") else model
    params = {k: v for k, v in clf.get_params().items()
              if v is not None and v != "deprecated" and k not in ("verbose", "n_jobs", "warm_start")}
    return f"`{type(clf).__name__}` " + ", ".join(f"{k}={v}" for k, v in sorted(params.items()))


def main():
    q4 = pd.read_csv(RESULTS / "q4_validation_metrics.csv")
    cv = pd.read_csv(RESULTS / "q4_cv_walk_forward.csv")
    trials = pd.read_csv(RESULTS / "q5_optuna_trials.csv")
    q5 = json.loads((RESULTS / "q5_test_result.json").read_text())
    abl = pd.read_csv(RESULTS / "q6_ablation.csv")
    mc = json.loads((RESULTS / "q6_mcnemar.json").read_text())
    q8 = json.loads((RESULTS / "q8_uncertainty.json").read_text())
    dash = json.loads((RESULTS / "dashboard_q4.json").read_text())

    lines = [
        "# Experiment log",
        "",
        f"Generated by `src/experiment_log.py` on {date.today().isoformat()} from the files in `results/`. "
        f"Random seed {SEED} everywhere. Split: train = feature years 2018–2021 (950 rows), validation = 2022 (244), "
        "test = 2023 (240, used once in Q5.3). Target = AGSA outcome in year t+1 (at_risk vs not_at_risk).",
        "",
        "## 1. Model configurations (Q3)",
        "",
    ]
    for name, model in build_models().items():
        lines.append(f"- **{name}:** {model_config(name, model)}")
    for name, info in dash["neural_history"].items():
        lines.append(f"- **{name}** early stopping: best epoch {info['best_epoch']}, stopped at epoch {info['epochs_run']}")

    lines += ["", "## 2. Validation-year results and walk-forward CV (Q4)", ""]
    t = q4[["model", "val_accuracy", "val_macro_f1", "val_recall_at_risk", "val_roc_auc", "val_pr_auc",
            "train_macro_f1"]].merge(cv[["model", "cv_macro_f1_mean", "cv_macro_f1_std"]], on="model")
    lines.append(md_table(t))

    lines += ["", f"## 3. Optimisation of the champion (Q5): {q5['search_method']}, {q5['n_trials']} trials", "",
              f"Scoring rule: {q5['scoring_rule']}. Best parameters: `{q5['best_params']}` "
              f"(CV macro-F1 {q5['best_cv_macro_f1']:.4f}). Top five trials:", ""]
    top = trials.sort_values("value", ascending=False).head(5)
    keep = ["number", "value"] + [c for c in top.columns if c.startswith("params_")]
    lines.append(md_table(top[keep].rename(columns={"value": "cv_macro_f1"}), "{:.4g}"))
    pp = pd.DataFrame(q5["pre_post"])[["config", "cv_macro_f1_mean", "val_macro_f1", "val_roc_auc"]]
    lines += ["", "Before and after:", "", md_table(pp)]
    tm = q5["test_metrics"]
    lines += ["", f"**One-time test evaluation** (fit 2018–2022, test 2023, n = {q5['n_test']}): "
              + ", ".join(f"{k} {v:.3f}" for k, v in tm.items()) + f"; confusion matrix {q5['test_confusion']}."]

    lines += ["", "## 4. Ablations (Q6.1) — fit 2018–2021, evaluated on 2022", ""]
    lines.append(md_table(abl[["experiment", "val_macro_f1", "delta_val_macro_f1", "val_roc_auc", "delta_val_roc_auc",
                               "cv_macro_f1_mean"]]))
    tb = mc["table"]
    lines += ["", "## 5. McNemar's test (Q6.2)", "",
              f"{mc['champion']} vs {mc['comparator']} on the same {mc['n_test']} test municipalities: "
              f"both correct {tb['both_correct']}, champion only {tb['champion_only_correct']}, "
              f"comparator only {tb['comparator_only_correct']}, both wrong {tb['both_wrong']}. "
              f"{mc['test_version']}, p = {mc['p_value']:.4f}, reject H0 at α = {mc['alpha']}: {mc['reject_H0']}.",
              "", "## 6. Uncertainty (Q8.1)", ""]
    ci = pd.DataFrame([{"metric": k, **v} for k, v in q8["metrics_ci95"].items()])
    lines += [md_table(ci), "", f"Brier score {q8['brier_score']:.3f}. Status changes in the test year: "
              f"{q8['status_changes_in_test']} (accuracy on them {q8['accuracy_on_status_changes']:.0%}; "
              f"on stable municipalities {q8['accuracy_on_stable']:.0%}). 2025 forecast: {q8['forecast_2025']}."]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
